"""Generate tests/fixtures/api.lua from a local Factorio install (dev tool).

Usage: python3 -I tests/tools/gen_api.py <Factorio .../Contents dir> <output.lua>
The output lists GUI element types, add() parameters, writable attributes,
LuaStyle attributes, style names with their types, utility sprite names and
event names, so the offline mock can reject what the real game would reject.
"""
import json, os, re, sys

contents, out_path = sys.argv[1], sys.argv[2]
api = json.load(open(os.path.join(contents, 'doc-html', 'runtime-api.json')))

def lua_str(s):
    return '"' + s.replace('\\', '\\\\').replace('"', '\\"') + '"'

def lua_set(items):
    return '{' + ','.join('[' + lua_str(x) + ']=true' for x in sorted(items)) + '}'

out = ['-- Generated by tests/tools/gen_api.py from Factorio %s. Do not edit.' % api['application_version'], 'return {']
for c in api['classes']:
    if c['name'] == 'LuaGuiElement':
        add = [m for m in c['methods'] if m['name'] == 'add'][0]
        common = [p['name'] for p in add['parameters']]
        out.append('  add_common = %s,' % lua_set(common))
        out.append('  add_variant = {')
        for g in add.get('variant_parameter_groups', []):
            out.append('    [%s] = %s,' % (lua_str(g['name']), lua_set(p['name'] for p in g['parameters'])))
        out.append('  },')
        writable = [a['name'] for a in c['attributes'] if a.get('write_type')]
        readable = [a['name'] for a in c['attributes'] if a.get('read_type')]
        out.append('  element_write = %s,' % lua_set(writable))
        out.append('  element_read = %s,' % lua_set(readable))
        out.append('  element_methods = %s,' % lua_set(m['name'] for m in c['methods']))
        out.append('  attr_types = {')
        for a in c['attributes']:
            if a.get('subclasses'):
                out.append('    [%s] = %s,' % (lua_str(a['name']), lua_set(a['subclasses'])))
        out.append('  },')
    if c['name'] == 'LuaRendering':
        m = [m for m in c['methods'] if m['name'] == 'draw_rectangle'][0]
        out.append('  draw_rectangle = %s,' % lua_set(p['name'] for p in m['parameters']))
    if c['name'] == 'LuaPlayer':
        m = [m for m in c['methods'] if m['name'] == 'set_controller'][0]
        out.append('  set_controller = %s,' % lua_set(p['name'] for p in m['parameters']))
    if c['name'] == 'LuaStyle':
        out.append('  style_write = %s,' % lua_set(a['name'] for a in c['attributes'] if a.get('write_type')))
        out.append('  style_attr_types = {')
        for a in c['attributes']:
            if a.get('subclasses'):
                out.append('    [%s] = %s,' % (lua_str(a['name']), lua_set(a['subclasses'])))
        out.append('  },')
for cpt in api['concepts']:
    if cpt['name'] == 'GuiElementType':
        out.append('  element_types = %s,' % lua_set(o['value'] for o in cpt['type']['options']))
out.append('  events = %s,' % lua_set(e['name'] for e in api['events']))

style_src = open(os.path.join(contents, 'data', 'core', 'prototypes', 'style.lua')).read()
styles = {}
for m in re.finditer(r'^    ([a-z0-9_]+) =\s*\n    \{(.*?)\n    \}', style_src, re.S | re.M):
    t = re.search(r'^      type = "([a-z_]+)"', m.group(2), re.M)
    if t:
        styles[m.group(1)] = t.group(1)
out.append('  styles = {')
for k in sorted(styles):
    out.append('    [%s] = %s,' % (lua_str(k), lua_str(styles[k])))
out.append('  },')

sprite_src = open(os.path.join(contents, 'data', 'core', 'prototypes', 'utility-sprites.lua')).read()
sprites = set(re.findall(r'^    ([a-z0-9_]+) =', sprite_src, re.M))
out.append('  utility_sprites = %s,' % lua_set(sprites))
out.append('}')
open(out_path, 'w').write('\n'.join(out) + '\n')
print('styles', len(styles), 'sprites', len(sprites))
